def write_sample(path: str | Path | None = None) -> Path:
    root = Path(__file__).resolve().parents[2]
    out = Path(path) if path else root / "data" / "sample" / "arxiv_sample.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(SAMPLE_DOCS, indent=2), encoding="utf-8")
    return out


